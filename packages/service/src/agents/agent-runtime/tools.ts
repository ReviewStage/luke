export function toolsOf(role: AgentRole): ReadonlySet<AgentTool> {
  return new Set(
    Object.values(AGENT_TOOL).filter((tool) => {
      const roles: readonly AgentRole[] = TOOL_ROLES[tool];
      return roles.includes(role);
    }),
  );
}
