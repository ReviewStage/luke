-- Expand step of dropping a pilot tree's switches, "task"."merge_policy", "task"."running", and
-- "turns"."cancel_requested_for_running": the modules no longer declare them, and nothing this deployment runs
-- reads or writes them. Note that the columns themselves stay one deployment longer, because a build migrates
-- while the deployment before it still serves and Drizzle names every declared column in an insert.
-- The task and turns tables' capture is rendered again without them, since a trigger whose WHEN names a column
-- is what a later DROP COLUMN would refuse over. Both tables are written on every turn and every save of a
-- plan, so they are locked first, as 20261029164210_task_merge_policy locks the task table, after GitLab's
-- with_lock_retries
-- (https://docs.gitlab.com/development/migration_style_guide/#retry-mechanism-when-acquiring-database-locks):
-- under a short lock_timeout of its own, letting the locks go and backing off holding none between attempts.
-- Nothing else this migration does locks a table but these two.
SET LOCAL statement_timeout = '150s';
--> statement-breakpoint
DO $$
DECLARE
	attempt int := 0;
	deadline timestamptz := clock_timestamp() + interval '2 minutes';
BEGIN
	LOOP
		attempt := attempt + 1;
		BEGIN
			PERFORM set_config('lock_timeout', least(100 * attempt, 500) || 'ms', true);
			LOCK TABLE "task", "turns" IN ACCESS EXCLUSIVE MODE;
			RETURN;
		EXCEPTION WHEN lock_not_available OR deadlock_detected THEN
			IF clock_timestamp() > deadline THEN
				RAISE;
			END IF;
		END;
		PERFORM pg_sleep(least(0.2 * attempt, 3) * (0.5 + random()));
	END LOOP;
END
$$;
